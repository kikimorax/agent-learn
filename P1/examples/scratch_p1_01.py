"""P1-01：用同一份活动通知比较无格式约束与限长总结。

在 P1 目录运行：uv run python examples/scratch_p1_01.py。
直接读取 UTF-8 源文件，避免用 PowerShell 管道传递中文代码。
运行脚本会发起两次真实模型请求；导入模块不会发起请求。
"""

from openai_client import get_completion_text

# 虚构教学材料：包含名额状态、不同付款期限及取消规则的例外。
# 两次请求必须复用相同材料，才能观察输出约束带来的变化。
text = """摄影工作坊限 20 人，满员后进入候补名单。
报名成功者须在 24 小时内付款，超时释放名额。
候补按登记顺序递补，收到通知后须在 6 小时内付款。
活动开始前至少 48 小时取消可全额退款；不足 48 小时不退款，但可在开始前转让一次名额。
主办方取消活动时，所有已付款报名者均可全额退款。"""

# 两版都要求只依据原文，仅第二版增加条数和长度约束。
# 格式合规不代表语义完整：重点核对付款时限、退款边界及主办方取消的例外。
prompts = (
    ("无格式约束", "总结这段文字，只依据原文：\n" + text),
    ("三条限长", "总结为三条，每条不超过15字，只依据原文：\n" + text),
)


def main() -> None:
    # 使用相同的客户端默认模型与参数，打印完整请求和回复便于记录。
    for label, prompt in prompts:
        print(f"\n=== {label} ===\n请求：\n{prompt}\n回复：", flush=True)
        print(get_completion_text(prompt))


if __name__ == "__main__":
    main()
